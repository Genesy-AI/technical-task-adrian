#!/usr/bin/env bash
# Prepares this checkout (the main one or any git worktree) to run alongside others:
#
#   - picks a free API port and frontend port, unique across all worktrees of the repo
#   - writes backend/.env and frontend/.env.local (never overwrites existing ones)
#   - gives the checkout its own Temporal namespace on the shared dev server
#   - installs dependencies and generates the Prisma client
#
# Idempotent: re-running keeps the existing env files and only redoes the cheap steps.
# Orca runs it on worktree creation (see orca.yaml); run it by hand anywhere else.
# Background: docs/adr/0001-per-worktree-runtime-config.md
set -euo pipefail

ROOT="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
cd "$ROOT"

API_PORT_BASE=4000
WEB_PORT_BASE=5173
TEMPORAL_ADDRESS_DEFAULT=localhost:7233

log() { printf '\033[1;34m[worktree-setup]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[worktree-setup]\033[0m %s\n' "$*" >&2; }

# --- Identity -----------------------------------------------------------------------
# The main checkout is "main"; a linked worktree is named after its directory.
if [[ "$(git rev-parse --git-dir)" == "$(git rev-parse --git-common-dir)" ]]; then
  SLUG=main
else
  SLUG="$(basename "$ROOT" | tr '[:upper:]' '[:lower:]' | tr -cs 'a-z0-9-' '-' | sed 's/^-*//; s/-*$//')"
fi
NAMESPACE="tinyenginy-${SLUG}"

# --- Port allocation ----------------------------------------------------------------
# Ports claimed by other worktrees' env files count as taken even when their servers
# are stopped, so a port stays with its worktree for the worktree's whole life.
read_var() { # <file> <var>
  [[ -f "$1" ]] && sed -n "s/^$2=[\"']\{0,1\}\([^\"']*\)[\"']\{0,1\}$/\1/p" "$1" | tail -n1
  return 0
}

claimed_ports() {
  git worktree list --porcelain | sed -n 's/^worktree //p' | while read -r wt; do
    [[ "$wt" == "$ROOT" ]] && continue
    read_var "$wt/backend/.env" PORT
    read_var "$wt/frontend/.env.local" VITE_PORT
  done
}

# A port is free if no other worktree claims it and nothing listens on it, except a
# server started from this very checkout (e.g. re-running setup while `pnpm dev` runs).
port_free() { # <port>
  grep -qx "$1" <<<"$CLAIMED" && return 1
  local pid cwd
  for pid in $(lsof -t -nP -iTCP:"$1" -sTCP:LISTEN 2>/dev/null); do
    cwd="$(lsof -a -p "$pid" -d cwd -Fn 2>/dev/null | sed -n 's/^n//p')"
    [[ "$cwd" == "$ROOT" || "$cwd" == "$ROOT"/* ]] || return 1
  done
  return 0
}

# The main checkout gets the base port; other worktrees search upwards from base+1, so
# the base port stays reserved for main even while main is not configured.
# Sets PICKED (no subshell, so CLAIMED is updated for the next pick).
pick_port() { # <base>
  local p=$(($1 + 1))
  if [[ $SLUG == main ]] && port_free "$1"; then p=$1; fi
  until port_free "$p"; do p=$((p + 1)); done
  CLAIMED+=$'\n'"$p"
  PICKED=$p
}

# Serialize allocation: Orca may create several worktrees at once.
LOCK="$(git rev-parse --git-common-dir)/worktree-setup.lock"
for _ in $(seq 1 100); do mkdir "$LOCK" 2>/dev/null && break; sleep 0.1; done
[[ -d "$LOCK" ]] || { warn "could not acquire $LOCK; remove it if stale"; exit 1; }
trap 'rmdir "$LOCK" 2>/dev/null || true' EXIT

CLAIMED="$(claimed_ports)"

if [[ -f backend/.env ]]; then
  log "backend/.env exists, keeping it"
else
  pick_port $API_PORT_BASE
  API_PORT=$PICKED
  cat >backend/.env <<EOF
# Generated by scripts/worktree-setup.sh for "$SLUG". See backend/.env.example.
PORT=$API_PORT
DATABASE_URL="file:./dev.db"
TEMPORAL_ADDRESS=$TEMPORAL_ADDRESS_DEFAULT
TEMPORAL_NAMESPACE=$NAMESPACE
TEMPORAL_TASK_QUEUE=tinyenginy
EOF
  log "wrote backend/.env (API port $API_PORT, Temporal namespace $NAMESPACE)"
fi
API_PORT="$(read_var backend/.env PORT)"

if [[ -f frontend/.env.local ]]; then
  log "frontend/.env.local exists, keeping it"
else
  pick_port $WEB_PORT_BASE
  WEB_PORT=$PICKED
  cat >frontend/.env.local <<EOF
# Generated by scripts/worktree-setup.sh for "$SLUG". Overrides frontend/.env.
VITE_API_URL=http://localhost:$API_PORT
VITE_PORT=$WEB_PORT
EOF
  log "wrote frontend/.env.local (web port $WEB_PORT)"
fi
WEB_PORT="$(read_var frontend/.env.local VITE_PORT)"

rmdir "$LOCK" 2>/dev/null || true
trap - EXIT

# --- Toolchain ----------------------------------------------------------------------
want_node="$(tr -d 'v[:space:]' <backend/.nvmrc)"
have_node="$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo none)"
[[ "$have_node" == "$want_node" ]] || warn "Node $want_node expected (.nvmrc), found $have_node; run 'nvm use' before developing"

# --- Dependencies -------------------------------------------------------------------
log "installing backend dependencies"
(cd backend && pnpm install --frozen-lockfile --reporter=append-only && pnpm gen:prisma)
log "installing frontend dependencies"
(cd frontend && pnpm install --frozen-lockfile --reporter=append-only)

# --- Temporal -----------------------------------------------------------------------
# Non-fatal: `pnpm dev` retries it, and the dev server may simply not be running yet.
if ! backend/scripts/ensure-temporal-namespace.sh; then
  warn "Temporal namespace not created yet; 'pnpm dev' will retry once the server is up"
fi

NS="$(read_var backend/.env TEMPORAL_NAMESPACE)"
log "done. Run in two terminals:"
log "  cd backend && pnpm dev    # API  → http://localhost:$API_PORT"
log "  cd frontend && pnpm dev   # Web  → http://localhost:$WEB_PORT"
log "Temporal UI: http://localhost:8233/namespaces/$NS/workflows"
